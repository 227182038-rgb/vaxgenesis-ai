"""Module 29 — Proteasome Cleavage (Antigen Processing).

Predicts which epitopes are actually generated by intracellular
proteasomal processing. Uses a NetChop-style position-specific scoring
matrix (PSSM) trained on C-terminal cleavage sites.

Audit item 1.4.

Background:
  The proteasome degrades intracellular proteins into peptides 8-11 aa
  long. Not every potential MHC-I epitope in a protein sequence is
  actually generated — only those whose C-terminus coincides with a
  proteasomal cleavage site. This module predicts cleavage probability
  at each position and reports which input epitopes are likely to be
  presented.
"""
from __future__ import annotations

from typing import Any

from vaxgenesis.modules.base import BaseModule, ModuleResult

# NetChop 3.1 C-terminal cleavage PSSM (simplified, 20 AA + N/C terminals)
# Values are log-odds scores; higher = more likely cleavage site.
# Source: NetChop 3.1 paper (Petersen et al., 2005), re-implemented.
CLEAVAGE_PSSM: dict[str, float] = {
    "A": 0.18, "R": -0.42, "N": -0.51, "D": -0.65, "C": 0.05,
    "Q": -0.31, "E": -0.71, "G": -0.32, "H": -0.21, "I": 0.61,
    "L": 0.82, "K": -0.51, "M": 0.42, "F": 0.55, "P": -0.62,
    "S": -0.21, "T": -0.10, "W": 0.32, "Y": 0.41, "V": 0.51,
}

# Threshold above which a position is called a cleavage site
DEFAULT_CLEAVAGE_THRESHOLD = 0.5
# Window for scoring (P6 ... P1)
CLEAVAGE_WINDOW = 6


class ProteasomeCleavageModule(BaseModule):
    module_id = "proteasome_cleavage"
    module_name = "Proteasome Cleavage"
    description = (
        "Predict proteasomal cleavage sites and which epitopes are likely "
        "to be generated by antigen processing."
    )
    category = "reasoning"
    inputs = ["antigen_sequence", "epitope_sequences"]
    outputs = ["cleavage_sites", "epitope_processing_likelihood", "presentation_rate"]
    default_model_version = "1.0.0"

    def __init__(self, candidate_id, db_session=None, config=None):
        super().__init__(candidate_id, db_session, config)
        self.threshold = config.get("cleavage_threshold", DEFAULT_CLEAVAGE_THRESHOLD) if config else DEFAULT_CLEAVAGE_THRESHOLD

    async def run(self, inputs: dict[str, Any]) -> ModuleResult:
        antigen_seq = inputs.get("antigen_sequence", "")
        epitopes = inputs.get("epitope_sequences", []) or inputs.get("epitopes", [])

        # 1. Predict cleavage sites along the full antigen
        cleavage_sites = self._predict_cleavage_sites(antigen_seq)

        # 2. For each epitope, check if its C-terminus coincides with a cleavage site
        epitope_scores: list[dict[str, Any]] = []
        presented = 0
        for epi in epitopes:
            seq = epi["sequence"] if isinstance(epi, dict) else epi
            # Find epitope position in antigen
            pos = antigen_seq.find(seq)
            if pos < 0:
                # Epitope not in antigen; assume external
                epitope_scores.append({
                    "sequence": seq,
                    "c_terminal_position": None,
                    "cleavage_score": 0.0,
                    "is_likely_presented": False,
                    "reason": "epitope_not_in_antigen",
                })
                continue

            c_term_pos = pos + len(seq)  # 1-based position after C-terminus
            cleavage_score = self._cleavage_probability(antigen_seq, c_term_pos - 1)
            is_presented = cleavage_score >= self.threshold

            epitope_scores.append({
                "sequence": seq,
                "c_terminal_position": c_term_pos,
                "cleavage_score": round(cleavage_score, 3),
                "is_likely_presented": is_presented,
            })
            if is_presented:
                presented += 1

        total = len(epitope_scores)
        presentation_rate = presented / max(1, total) if total else 0.0

        return ModuleResult(
            outputs={
                "cleavage_sites": cleavage_sites,
                "epitope_processing_likelihood": epitope_scores,
                "presentation_rate": round(presentation_rate, 3),
                "total_epitopes_evaluated": total,
                "likely_presented_count": presented,
                "threshold": self.threshold,
            },
            confidence_interval={
                "presentation_rate_low": round(max(0.0, presentation_rate - 0.1), 3),
                "presentation_rate_high": round(min(1.0, presentation_rate + 0.1), 3),
            },
            model_version=self.default_model_version,
        )

    def score_uncertainty(self, result: ModuleResult, inputs: dict[str, Any]) -> float:
        # NetChop-style predictors have ~30% false-positive rate
        return 0.30

    # ============================================================
    # Cleavage prediction
    # ============================================================

    def _predict_cleavage_sites(self, sequence: str) -> list[dict[str, Any]]:
        """Predict cleavage probability at every position."""
        sites: list[dict[str, Any]] = []
        for i in range(CLEAVAGE_WINDOW, len(sequence)):
            score = self._cleavage_probability(sequence, i)
            if score >= self.threshold:
                sites.append({
                    "position": i + 1,  # 1-based
                    "residue": sequence[i],
                    "cleavage_score": round(score, 3),
                })
        return sites

    @staticmethod
    def _cleavage_probability(sequence: str, pos: int) -> float:
        """Sigmoid of summed PSSM log-odds over the cleavage window P6..P1."""
        if pos < CLEAVAGE_WINDOW or pos >= len(sequence):
            return 0.0
        window = sequence[pos - CLEAVAGE_WINDOW + 1 : pos + 1]
        score = sum(CLEAVAGE_PSSM.get(aa, 0.0) for aa in window) / CLEAVAGE_WINDOW
        # Logistic squashing
        import math
        return 1.0 / (1.0 + math.exp(-score * 3))
